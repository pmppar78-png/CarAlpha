const BANNED = /\b(other|foundation|components)\b|[:/]/i;

function normKey(component) {
  return String(component || "")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .replace(/\s*:\s*/g, ":")
    .trim();
}

function scrub(phrase) {
  return String(phrase || "")
    .replace(/[:/]+/g, " ")
    .replace(/\b(other|foundation|components)\b/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function firstClause(summary) {
  const raw = String(summary || "").replace(/\s+/g, " ").trim();
  if (!raw) return "";
  const cut = raw.split(/[.?;]/)[0].trim();
  if (!cut || cut.length > 80) return "";
  if (/is recalling|are recalling/i.test(cut)) return "";
  const phrase = scrub(cut.charAt(0).toLowerCase() + cut.slice(1));
  if (!phrase || BANNED.test(phrase)) return "";
  return phrase;
}

const EXACT_NORM = {};
for (const [key, label] of Object.entries(EXACT)) EXACT_NORM[normKey(key)] = label;

function plainRecallLabel(component, summary) {
  const key = normKey(component);
  if (EXACT_NORM[key]) return EXACT_NORM[key];
  const fromSummary = firstClause(summary);
  if (fromSummary) return fromSummary;
  return "recalled part";
}

const ABBR = /\b(?:Inc|Corp|Ltd|LLC|LLP|Co|U\.S|No|Mr|Mrs|Ms|St|Jr|Sr|vs|Dept|Fig)\.$/i;

function splitSentences(raw) {
  const parts = [];
  let start = 0;
  const re = /[.?!]["']?(?=\s)/g;
  let match;
  while ((match = re.exec(raw))) {
    const end = match.index + match[0].length;
    const sentence = raw.slice(start, end).trim();
    if (ABBR.test(sentence.replace(/["']$/, "")) && !/["']/.test(match[0])) continue;
    parts.push(sentence);
    start = end;
    while (raw[start] === " ") start += 1;
    re.lastIndex = start;
  }
  const tail = raw.slice(start).trim();
  if (tail) parts.push(tail);
  return parts.filter(Boolean);
}

function finishSentence(pick) {
  let text = String(pick || "").trim().replace(/(["'])\.+$/, "$1");
  if (!text) return "";
  if (/[.?!]["']?$/.test(text)) return text;
  return text + ".";
}

function oneSentence(text) {
  const raw = String(text || "").replace(/\s+/g, " ").trim();
  if (!raw) return "";
  const parts = splitSentences(raw);
  const boiler = (part) => /\bsee the recall report\b/i.test(part);
  const useful = parts.filter((part) => !boiler(part) && !/\b(is|are) recalling\b/i.test(part) && part.split(/\s+/).length >= 4);
  const pick = useful[0] || parts.find((part) => !boiler(part) && !/\b(is|are) recalling\b/i.test(part)) || parts.find((part) => !boiler(part)) || parts[0] || "";
  const done = finishSentence(pick);
  return done.charAt(0).toUpperCase() + done.slice(1);
}

